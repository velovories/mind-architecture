export const STRINGS: Record<Lang, Strings> = { ru, uk };
export const LANG_NAMES: Record<Lang, string> = { ru: "Русский", uk: "Українська" };

/** Every heading name the plugin has ever used for its links section, in any language. */
export const SECTION_NAMES = [ru.section, uk.section];

let current: Lang = "ru";
export const setLang = (l: Lang) => { current = l; };
export const getLang = () => current;

type TextKey = { [K in keyof Strings]: Strings[K] extends string ? K : never }[keyof Strings];

export function t(key: TextKey, params: Record<string, string | number> = {}): string {
  return STRINGS[current][key].replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ""));
}

export const kinds = () => STRINGS[current].kinds;
export const confidences = () => STRINGS[current].confidence;
